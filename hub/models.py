"""
Pydantic v2 Data Models for Julius Hub.
Defines schemas for engine orchestration, worktree lifecycle, suggestions, escalation,
community settings, and session records.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator


class EngineMode(str, Enum):
    """Execution mode for scanning and patch generation."""
    ANTIGRAVITY_FLASH = "antigravity_flash"
    LOCAL = "local"
    HYBRID = "hybrid"


class TaskStatus(str, Enum):
    """Lifecycle status of a curation or escalation task."""
    PENDING = "pending"
    RUNNING = "running"
    TESTING = "testing"
    PASSED = "passed"
    RETRY = "retry"
    FAILED = "failed"
    NEEDS_ESCALATION = "needs_escalation"
    READY_FOR_SENIOR = "ready_for_senior"
    NEEDS_SENIOR_FIX = "needs_senior_fix"
    COMPLETED = "completed"


class GitAuthoringMode(str, Enum):
    """Authoring attribution mode for git commits."""
    CO_AUTHORED = "co_authored"
    JULIUS_ONLY = "julius_only"
    JULES_ONLY = "jules_only"
    USER_ONLY = "user_only"


class CommunitySettings(BaseModel):
    """Community configuration settings for Julius Hub v3."""
    model_config = ConfigDict(extra="ignore")

    default_model: str = "Gemini 3.1 Pro"
    auto_find_issues: bool = True
    export_as_pr: bool = True
    git_commit_authoring: GitAuthoringMode = GitAuthoringMode.CO_AUTHORED
    only_respond_to_mentions: bool = False
    open_pr_as_draft: bool = False
    cdp_url: str = "http://127.0.0.1:9000"
    workspaces_root: str = ""
    github_token_masked: Optional[str] = None
    cloud_api_key_masked: Optional[str] = None
    has_github_token: bool = False
    has_cloud_api_key: bool = False

    @field_validator("git_commit_authoring", mode="before")
    @classmethod
    def normalize_git_commit_authoring(cls, value: Any) -> Any:
        if value in ("jules_only", GitAuthoringMode.JULES_ONLY):
            return GitAuthoringMode.JULIUS_ONLY
        return value


class SecretsUpdateRequest(BaseModel):
    """Request payload to update sensitive tokens and API keys."""
    model_config = ConfigDict(extra="ignore")

    github_token: Optional[str] = None
    gemini_api_key: Optional[str] = None
    openai_api_key: Optional[str] = None


class SessionRecord(BaseModel):
    """Record of an executed prompt or curation session."""
    model_config = ConfigDict(extra="ignore")

    task_id: str
    repo: str
    title: str
    prompt: Optional[str] = None
    persona: str = "bolt"
    status: TaskStatus = TaskStatus.PENDING
    branch: Optional[str] = None
    worktree_path: Optional[str] = None
    diff: Optional[str] = None
    pr_url: Optional[str] = None
    created_at: str


class Suggestion(BaseModel):
    """A single micro-improvement suggestion generated by the scanner."""
    model_config = ConfigDict(extra="ignore")

    id: str
    persona: str
    category: str
    title: str
    file: str
    line: int
    issue: str
    impact: str
    code_snippet: str

    def get(self, key: str, default: Any = None) -> Any:
        """Allow dict-like get access for backward compatibility."""
        return getattr(self, key, default)

    def __getitem__(self, key: str) -> Any:
        """Allow dict-like subscription access."""
        try:
            return getattr(self, key)
        except AttributeError:
            raise KeyError(key)


class WorktreeSessionInfo(BaseModel):
    """Metadata describing an isolated git worktree session."""
    model_config = ConfigDict(extra="ignore")

    worktree_path: str
    branch: str
    repo_name: str
    persona: str
    created_at: Optional[str] = None
    is_active: bool = True


class RunRequest(BaseModel):
    """Request payload to initiate a curation task in a worktree."""
    model_config = ConfigDict(extra="ignore")

    repo: str
    persona: str = "bolt"
    target_file: Optional[str] = None
    issue_context: Optional[str] = None
    prompt: Optional[str] = None
    mode: EngineMode = EngineMode.ANTIGRAVITY_FLASH
    branch: Optional[str] = None
    dry_run: bool = False


class RunResponse(BaseModel):
    """Response returned upon launching a curation task."""
    model_config = ConfigDict(extra="ignore")

    task_id: str
    status: TaskStatus = TaskStatus.PENDING
    worktree_path: Optional[str] = None
    branch: Optional[str] = None
    diff: Optional[str] = None
    message: str = ""


class EscalateRequest(BaseModel):
    """Request payload to escalate a worktree to Antigravity Senior Review via CDP."""
    model_config = ConfigDict(extra="ignore")

    repo: str
    worktree_path: str
    branch: str
    diff_summary: str
    test_status: str
    instruction: str = "Esegui audit Senior. Se approvato, apri la PR su GitHub."


class EscalateResponse(BaseModel):
    """Response returned after attempting Senior Review escalation."""
    model_config = ConfigDict(extra="ignore")

    success: bool
    message: str
    target_url: Optional[str] = None


class WorktreePruneRequest(BaseModel):
    """Request payload to prune one or all worktrees."""
    model_config = ConfigDict(extra="ignore")

    worktree_path: Optional[str] = None
    repo_name: Optional[str] = None
    force: bool = True


class PatchResult(BaseModel):
    """Result of an engine patch attempt (< 50 lines)."""
    model_config = ConfigDict(extra="ignore")

    success: bool
    diff: Optional[str] = None
    lines_changed: int = 0
    error: Optional[str] = None
    engine_used: Optional[str] = None


class CDPResponse(BaseModel):
    """Response from Antigravity Chrome DevTools Protocol bridge."""
    model_config = ConfigDict(extra="ignore")

    success: bool
    message: str = ""
    response_data: Optional[Dict[str, Any]] = None


class PersonaConfig(BaseModel):
    """Configuration for a curation persona (Bolt, Palette, Sentinel)."""
    model_config = ConfigDict(extra="ignore")

    name: str
    role: str
    mission: str
    icon: str
    focus: List[str] = Field(default_factory=list)
    avoids: List[str] = Field(default_factory=list)
    pr_prefix: str


class ProjectInfo(BaseModel):
    """Repository info registered in projects_registry.json."""
    model_config = ConfigDict(extra="ignore")

    name: str
    path: str
    description: Optional[str] = ""
    active_branch: Optional[str] = None


