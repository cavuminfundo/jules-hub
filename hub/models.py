"""
Pydantic v2 Data Models for Jules Hub.
Defines schemas for engine orchestration, worktree lifecycle, suggestions, and escalation.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class EngineMode(str, Enum):
    """Execution mode for scanning and patch generation."""
    ANTIGRAVITY_FLASH = "antigravity_flash"
    LOCAL = "local"
    HYBRID = "hybrid"


class TaskStatus(str, Enum):
    """Lifecycle status of a curation or escalation task."""
    PENDING = "pending"
    RUNNING = "running"
    TESTING = "testing"
    PASSED = "passed"
    RETRY = "retry"
    FAILED = "failed"
    NEEDS_ESCALATION = "needs_escalation"
    COMPLETED = "completed"


class Suggestion(BaseModel):
    """A single micro-improvement suggestion generated by the scanner."""
    model_config = ConfigDict(extra="ignore")

    id: str
    persona: str
    category: str
    title: str
    file: str
    line: int
    issue: str
    impact: str
    code_snippet: str

    def get(self, key: str, default: Any = None) -> Any:
        """Allow dict-like get access for backward compatibility."""
        return getattr(self, key, default)

    def __getitem__(self, key: str) -> Any:
        """Allow dict-like subscription access."""
        try:
            return getattr(self, key)
        except AttributeError:
            raise KeyError(key)


class WorktreeSessionInfo(BaseModel):
    """Metadata describing an isolated git worktree session."""
    model_config = ConfigDict(extra="ignore")

    worktree_path: str
    branch: str
    repo_name: str
    persona: str
    created_at: Optional[str] = None
    is_active: bool = True


class RunRequest(BaseModel):
    """Request payload to initiate a curation task in a worktree."""
    model_config = ConfigDict(extra="ignore")

    repo: str
    persona: str = "bolt"
    target_file: Optional[str] = None
    issue_context: Optional[str] = None
    mode: EngineMode = EngineMode.ANTIGRAVITY_FLASH
    branch: Optional[str] = None
    dry_run: bool = False


class RunResponse(BaseModel):
    """Response returned upon launching a curation task."""
    model_config = ConfigDict(extra="ignore")

    task_id: str
    status: TaskStatus = TaskStatus.PENDING
    worktree_path: Optional[str] = None
    branch: Optional[str] = None
    message: str = ""


class EscalateRequest(BaseModel):
    """Request payload to escalate a worktree to Antigravity Senior Review via CDP."""
    model_config = ConfigDict(extra="ignore")

    repo: str
    worktree_path: str
    branch: str
    diff_summary: str
    test_status: str
    instruction: str = "Esegui audit Senior. Se approvato, apri la PR su GitHub."


class EscalateResponse(BaseModel):
    """Response returned after attempting Senior Review escalation."""
    model_config = ConfigDict(extra="ignore")

    success: bool
    message: str
    target_url: Optional[str] = None


class WorktreePruneRequest(BaseModel):
    """Request payload to prune one or all worktrees."""
    model_config = ConfigDict(extra="ignore")

    worktree_path: Optional[str] = None
    repo_name: Optional[str] = None
    force: bool = True


class PatchResult(BaseModel):
    """Result of an engine patch attempt (< 50 lines)."""
    model_config = ConfigDict(extra="ignore")

    success: bool
    diff: Optional[str] = None
    lines_changed: int = 0
    error: Optional[str] = None
    engine_used: Optional[str] = None


class CDPResponse(BaseModel):
    """Response from Antigravity Chrome DevTools Protocol bridge."""
    model_config = ConfigDict(extra="ignore")

    success: bool
    message: str = ""
    response_data: Optional[Dict[str, Any]] = None


class PersonaConfig(BaseModel):
    """Configuration for a curation persona (Bolt, Palette, Sentinel)."""
    model_config = ConfigDict(extra="ignore")

    name: str
    role: str
    mission: str
    icon: str
    focus: List[str] = Field(default_factory=list)
    avoids: List[str] = Field(default_factory=list)
    pr_prefix: str


class ProjectInfo(BaseModel):
    """Repository info registered in projects_registry.json."""
    model_config = ConfigDict(extra="ignore")

    name: str
    path: str
    description: Optional[str] = ""
    active_branch: Optional[str] = None


